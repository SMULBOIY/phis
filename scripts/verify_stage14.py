# 5. Clean production start
# --------------------------------------------------------------------------- #
def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def fetch(url: str, timeout: float = 10.0) -> tuple[int, dict[str, str], bytes]:
    with urllib.request.urlopen(url, timeout=timeout) as response:  # noqa: S310 - loopback only
        return response.status, dict(response.headers), response.read()


def check_production_start() -> None:
    section("5. Clean production start (waitress + wsgi:create_application)")
    executable = Path(sys.executable).parent / "waitress-serve"
    if not executable.exists():
        candidate = Path(sys.executable).parent / "waitress-serve.exe"
        if candidate.exists():
            executable = candidate
    check("waitress-serve console script is installed", executable.exists(), str(executable))
    if not executable.exists():
        return

    port = free_port()
    env = dict(os.environ)
    env["APP_ENV"] = "production"
    env["SECRET_KEY"] = "9f" * 32                    # deterministic, local, never used elsewhere
    env["HOST"] = "127.0.0.1"
    env["PORT"] = str(port)

    # Options BEFORE the module spec: waitress parses the module positionally.
    command = [str(executable), "--call", f"--listen=127.0.0.1:{port}", "wsgi:create_application"]
    print("        " + " ".join(command))

    process = subprocess.Popen(  # noqa: S603 - fixed argv, loopback only
        command, cwd=str(ROOT), env=env,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    )
    log_lines: list[str] = []
    try:
        base = f"http://127.0.0.1:{port}"
        status, headers, body = 0, {}, b""
        deadline = time.time() + 30
        while time.time() < deadline:
            if process.poll() is not None:
                break
            try:
                status, headers, body = fetch(f"{base}/health", timeout=2)
                break
            except (urllib.error.URLError, ConnectionError, OSError):
                time.sleep(0.4)

        check("server answered /health with 200", status == 200, f"status {status}")
        if status != 200:
            return

        health = json.loads(body)
        check("health reports status ok", health.get("status") == "ok", str(health.get("status")))
        check("health reports version 0.14.0", health.get("version") == "0.14.0",
              str(health.get("version")))
        check("health reports build_stage 14", health.get("build_stage") == 14,
              str(health.get("build_stage")))
        check("health reports production environment",
              health.get("environment") == "production", str(health.get("environment")))
        check("bundle is available and hash-verified",
              health.get("bundle", {}).get("available") is True,
              str(health.get("bundle", {}).get("detail")))
        check("database is ready",
              health.get("database", {}).get("status") == "ready",
              str(health.get("database", {}).get("status")))
        check("detection engine is ready",
              health.get("detection", {}).get("status") == "ready")
        thresholds = health.get("detection", {}).get("decision_thresholds", {})
        check("measured thresholds served at runtime",
              (thresholds.get("low"), thresholds.get("high")) == (0.05, 0.95), str(thresholds))

        server_header = {k.lower(): v for k, v in headers.items()}
        check("served by waitress", server_header.get("server") == "waitress",
              str(server_header.get("server")))
        check("production CSP present",
              "default-src 'self'" in server_header.get("content-security-policy", ""))
        check("no CDN allowed by CSP",
              "http" not in server_header.get("content-security-policy", "").replace(
                  "connect-src 'self'", ""))
        check("HSTS present in production",
              "max-age=" in server_header.get("strict-transport-security", ""))
        check("X-Frame-Options DENY", server_header.get("x-frame-options") == "DENY",
              str(server_header.get("x-frame-options")))
        check("X-Content-Type-Options nosniff",
              server_header.get("x-content-type-options") == "nosniff")
        check("Referrer-Policy present", "referrer-policy" in server_header)

        # The other three surfaces the deployment guide promises.
        for path in ("/api/v1/health", "/api/v1/model/info", "/"):
            try:
                path_status, _, path_body = fetch(f"{base}{path}")
            except (urllib.error.URLError, OSError) as exc:
                check(f"GET {path} served", False, str(exc))
                continue
            check(f"GET {path} served", path_status == 200, f"status {path_status}")
            if path == "/api/v1/health":
                payload = json.loads(path_body)
                check("API health exposes app_version",
                      payload.get("app_version") == "0.14.0", str(payload.get("app_version")))
            if path == "/api/v1/model/info":
                payload = json.loads(path_body)
                check("model card lists 15 features",
                      len(payload.get("model", {}).get("feature_order", [])) == 15)
                check("model card cites metrics.json as the source",
                      "metrics.json" in json.dumps(payload))

        # CSRF must still guard the JSON write path, even in production.
        request = urllib.request.Request(
            f"{base}/api/v1/scan", method="POST",
            data=json.dumps({"url": "https://example.com/"}).encode(),
            headers={"Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=10) as response:  # noqa: S310
                csrf_status = response.status
        except urllib.error.HTTPError as exc:
            csrf_status = exc.code
        check("POST /api/v1/scan without a token is rejected", csrf_status == 400,
              f"status {csrf_status}")

    finally:
        process.terminate()
        try:
            output, _ = process.communicate(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            output, _ = process.communicate()
        log_lines = (output or "").splitlines()
        print("        --- server output ---")
        for line in log_lines[:12]:
            print(f"        {line}")

    check("server exited after SIGTERM", process.returncode is not None)
    check("start-up log names the deployed stage",
          any("stage=14" in line for line in log_lines), " | ".join(log_lines[:3]))
    check("no traceback in the server output",
          not any("Traceback (most recent call last)" in line for line in log_lines))


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #
def main() -> int:
    print("=" * 78)
    print("STAGE 14 EXIT GATE - documentation integrity and clean production start")
    print("=" * 78)

    check_deliverables()
    check_diagrams()
    check_stage_discipline()
    check_numeric_provenance()
    check_production_start()

    print("\n" + "=" * 78)
    print(f"CHECKS: {CHECKS}  SKIPPED: {SKIPPED}  FAILURES: {len(FAILURES)}")
    if FAILURES:
        print("RESULT: FAIL")
        for failure in FAILURES:
            print(f"  - {failure}")
        print("=" * 78)
        return 1
    print("RESULT: PASS")
    print("=" * 78)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
