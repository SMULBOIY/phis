def check(label: str, condition: Any, detail: str = "") -> None:
    """Record one binary assertion."""
    global CHECKS
    CHECKS += 1
    ok = bool(condition)
    if not ok:
        FAILURES.append(f"{label} :: {detail}" if detail else label)
        print(f"  FAIL  {label}" + (f" :: {detail}" if detail else ""))
    else:
        print(f"  ok    {label}")


def skip(label: str, reason: str) -> None:
    global SKIPPED
    SKIPPED += 1
    print(f"  skip  {label} :: {reason}")


def read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def section(title: str) -> None:
    print(f"\n[{title}]")


# --------------------------------------------------------------------------- #
# Numeric provenance: no hand-typed metric may appear in the report
# --------------------------------------------------------------------------- #
def json_numbers(node: Any, acc: set[float]) -> set[float]:
    if isinstance(node, bool):
        return acc
    if isinstance(node, (int, float)):
        acc.add(float(node))
    elif isinstance(node, dict):
        for value in node.values():
            json_numbers(value, acc)
    elif isinstance(node, list):
        for value in node:
            json_numbers(value, acc)
    elif isinstance(node, str):
        for token in re.findall(r"-?\d+\.\d+", node):
            with contextlib.suppress(ValueError):
                acc.add(float(token))
    return acc


def measured_values() -> set[float]:
    values: set[float] = set()
    for path in (METRICS, METADATA):
        if path.is_file():
            json_numbers(json.loads(read(path)), values)
    return values


def report_decimals(text: str) -> list[tuple[str, int]]:
    """Every decimal with 4+ fractional digits, with its printed precision.

    Citations and URLs are excluded: a DOI such as 10.1016/j.cose.2023.103545 is
    a bibliographic identifier, not a claim about the system. A typographic
    minus (U+2212) is normalised and magnitudes are compared, so a rounded
    "-1e-06" in the artefact matches "0.000001" in the report.
    """
    body = text.split("\n# References", 1)[0]
    body = re.sub(r"https?://\S+", " ", body)
    body = body.replace("\u2212", "-")
    found: list[tuple[str, int]] = []
    for token in re.findall(r"-?\d+\.\d{4,}", body):
        decimals = len(token.split(".")[1])
        found.append((token.lstrip("-"), decimals))
    return found


def check_numeric_provenance() -> None:
    section("4. Numeric provenance of the report")
    if not REPORT.is_file():
        skip("report numeric provenance", "docs/REPORT.md is missing")
        return
    try:
        values = measured_values()
    except json.JSONDecodeError as exc:  # pragma: no cover - defensive
        check("model artefacts are readable JSON", False, str(exc))
        return
    check("model artefacts expose measured numbers", len(values) > 100, f"{len(values)} values")

    tokens = report_decimals(read(REPORT))
    check("report prints measured decimals", len(tokens) >= 40, f"{len(tokens)} decimals")

    unknown: list[str] = []
    for token, decimals in tokens:
        target = round(float(token), decimals)
        if not any(round(abs(value), decimals) == target for value in values):
            unknown.append(token)

    check(
        "every reported decimal exists in metrics.json/metadata.json",
        not unknown,
        "hand-typed candidates: " + ", ".join(sorted(set(unknown))[:12]),
    )
    print(f"        ({len(tokens)} decimals checked against {len(values)} measured values)")


