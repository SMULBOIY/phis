def check_deliverables() -> None:
    section("1. Stage 14 deliverables")
    for rel in ("docs/REPORT.md", "docs/DEPLOYMENT.md", "README.md",
                "docs/STAGE_PLAN.md", "docs/DECISIONS.md", "docs/ARCHITECTURE.md"):
        check(f"deliverable exists :: {rel}", (ROOT / rel).is_file())
    for name in REQUIRED_DIAGRAMS:
        check(f"diagram exists :: docs/diagrams/{name}", (DIAGRAMS / name).is_file())

    report = read(REPORT)
    check("report is substantive (>= 700 lines)", report.count("\n") >= 700,
          f"{report.count(chr(10))} lines")
    for heading in REQUIRED_REPORT_HEADINGS:
        check(f"report contains heading :: {heading}", heading in report)
    for required in ("Abstract", "Table of contents", "Appendix A"):
        check(f"report contains section :: {required}", required in report)

    # The limitations chapter must name the three honest disclosures.
    limitations = report.split("Limitations and threats to validity", 1)[-1]
    for phrase in ("HTTPS", "56.90", "100.00", "abstention", "uncalibrated", "Static"):
        check(f"limitations name :: {phrase}", phrase in limitations)

    deployment = read(DEPLOYMENT)
    check("deployment guide names the exact gate command",
          "waitress-serve --call wsgi:create_application" in deployment.replace("\n", " ")
          or "waitress-serve --call wsgi:create_application" in deployment)
    check("deployment guide gives the PowerShell waitress path",
          "Scripts\\waitress-serve.exe" in deployment)
    check("deployment guide gives PowerShell pytest",
          ".venv\\Scripts\\python.exe" in deployment or ".venv\\Scripts\\Activate.ps1" in deployment)
    for topic in ("SECRET_KEY", "reverse proxy", "systemd", "Backup", "Troubleshooting"):
        check(f"deployment guide covers :: {topic}", topic in deployment)


# --------------------------------------------------------------------------- #
# 2. Offline-safe diagrams
# --------------------------------------------------------------------------- #
def check_diagrams() -> None:
    section("2. UML diagrams render offline")
    for name in REQUIRED_DIAGRAMS:
        path = DIAGRAMS / name
        if not path.is_file():
            skip(f"well-formed SVG :: {name}", "missing")
            continue
        text = read(path)
        try:
            root = ET.fromstring(text)
            parsed = True
        except ET.ParseError as exc:
            root = None
            parsed = False
            check(f"well-formed XML :: {name}", False, str(exc))
            continue
        check(f"well-formed XML :: {name}", parsed)
        check(f"root element is svg :: {name}",
              root is not None and root.tag.split("}")[-1] == "svg")
        lowered = text.lower()
        external = re.findall(r'(?:href|src)\s*=\s*["\'](?:https?:)?//', lowered)
        check(f"no external reference :: {name}", not external, ", ".join(external[:3]))
        check(f"no script element :: {name}", "<script" not in lowered)
        check(f"no raster image :: {name}", "<image" not in lowered)
        check(f"no remote font import :: {name}", "@import" not in lowered and "fonts.googleapis" not in lowered)
        check(f"declares a viewBox :: {name}", "viewbox" in lowered)
        check(f"is not a stub (>= 40 elements) :: {name}",
              len(list(root.iter())) >= 40, f"{len(list(root.iter()))} elements")


