#!/usr/bin/env python3
"""Stage 14 exit gate: documentation integrity and a clean production start.

Run from the project root (Windows or Linux):

    python scripts\\verify_stage14.py       (Windows)
    ./scripts/verify_stage14.py            (Linux/macOS)
    ./.venv/bin/python scripts/verify_stage14.py

Stage 14 adds no feature and changes no test, so this gate verifies two things
that can be checked objectively rather than argued about:

  * DOCUMENTATION INTEGRITY
      - docs/REPORT.md exists and contains chapters 1-5, the required
        sections and an explicit limitations section;
      - every UML diagram under docs/diagrams/ is well-formed SVG, has no
        external reference, no <script> and no raster <image>, so it renders
        offline in a browser, a Word document or a diagram tool;
      - docs/DEPLOYMENT.md exists, names the exact waitress command, and gives
        PowerShell equivalents (this project is Windows-first);
      - NO FABRICATED NUMBERS: every decimal printed to 4+ places in
        docs/REPORT.md must exist in ml/saved_model/metrics.json or
        metadata.json, which are generated by measurement. A hand-typed metric
        fails this check.

  * CLEAN PRODUCTION START
      - `waitress-serve --call wsgi:create_application` is launched in a real
        subprocess with APP_ENV=production on a free loopback port;
      - /health, /api/v1/health, /api/v1/model/info and / must answer 200;
      - the app must report the deployed stage and version, a hash-verified
        bundle, a ready database and the measured thresholds;
      - production security headers must be present, and the process must
        terminate cleanly.

  * STAGE DISCIPLINE
      - route count, blueprint count and blueprint set are unchanged from
        Stage 13 (22 application rules);
      - the six test modules still exist and no test file was added.

The gate never contacts a live website, never resolves a user-supplied URL and
never reaches the public internet.
"""
